import fs from 'node:fs';

const read = (file) => fs.readFileSync(new URL(`../${file}`, import.meta.url), 'utf8');
const json = (file) => JSON.parse(read(file));
const fail = (message) => {
  throw new Error(`supply-chain verification failed: ${message}`);
};

const root = json('package.json');
const web = json('web/package.json');
const exactVersion = /^\d+\.\d+\.\d+(?:-[0-9A-Za-z.-]+)?$/;

for (const [manifest, pkg] of [
  ['package.json', root],
  ['web/package.json', web],
]) {
  for (const field of ['dependencies', 'devDependencies', 'resolutions']) {
    for (const [name, version] of Object.entries(pkg[field] ?? {})) {
      if (!exactVersion.test(version)) fail(`${manifest} ${field}.${name} is not exact: ${version}`);
    }
  }
}

const nodeVersion = read('.nvmrc').trim();
if (nodeVersion !== read('.node-version').trim()) fail('.nvmrc and .node-version differ');
if (root.engines?.node !== nodeVersion) fail('package.json engines.node differs from toolchain pin');
if (!/^yarn@\d+\.\d+\.\d+$/.test(root.packageManager ?? '')) {
  fail('packageManager must pin an exact Yarn version');
}
const yarnSha = root.supplyChain?.yarnTarballSha256;
if (!/^[0-9a-f]{64}$/.test(yarnSha ?? '')) fail('Yarn tarball SHA-256 is not pinned');
for (const installer of ['install.sh', 'install.ps1']) {
  if (!read(installer).includes(yarnSha)) fail(`${installer} does not use the pinned Yarn hash`);
}

for (const lock of ['yarn.lock', 'web/yarn.lock']) {
  const body = read(lock);
  if (!body.startsWith('# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.')) {
    fail(`${lock} is not a Yarn v1 lockfile`);
  }
  if (!body.includes('\n  integrity sha512-')) fail(`${lock} has no integrity records`);
}

const workflow = read('.github/workflows/verify.yml');
for (const line of workflow.split('\n').filter((line) => line.includes('uses:'))) {
  if (!/uses:\s+[A-Za-z0-9_.-]+\/[A-Za-z0-9_.-]+@[0-9a-f]{40}(?:\s|$)/.test(line)) {
    fail(`GitHub Action is not commit-pinned: ${line.trim()}`);
  }
}

const updater = read('src/server/updater.ts');
if (/raw\.githubusercontent\.com\/[^`'"\s]+\/main\/install\.(?:sh|ps1)/.test(updater)) {
  fail('updater still executes an installer from mutable main');
}
if (updater.includes('...process.env')) fail('updater forwards the complete process environment');

console.log(`Supply chain pinned: Node ${nodeVersion}, ${root.packageManager.split('+')[0]}.`);
